#include <array>
#include <cmath>
#include <cstddef>
#include <vector>

#include "autopas/utils/ArrayMath.h"
#include "autopas/utils/Math.h"
#include "autopas/utils/Quaternion.h"
#include "autopasdm/BoundaryType.h"

/**
 * Application-level reflective Lennard-Jones wall used by md-flexible.
 *
 * AutoPasDM models reflective boundaries as non-periodic communication
 * boundaries. The physical wall interaction is handled here because it
 * depends on Lennard-Jones particle properties.
 *
 * Single-site particles interact with their mirror image. For multisite
 * molecules, every site interacts with every site of the mirrored molecule.
 * The resulting forces and torques are kept only if their net force points
 * away from the wall, matching the original md-flexible implementation.
 */
namespace ReflectiveBoundary {
namespace detail {

inline constexpr double sixthRootOfTwo = 1.122462048309373;

/**
 * Calculate the Lennard-Jones force between two sites.
 *
 * @param position Position of the site receiving the force.
 * @param otherPosition Position of the site generating the force.
 * @param sigmaSquared Squared Lennard-Jones sigma value.
 * @param epsilon24 Twenty-four times the Lennard-Jones epsilon value.
 * @return Force acting on the site.
 */
inline std::array<double, 3> calculateLJForce(const std::array<double, 3> &position,
                                              const std::array<double, 3> &otherPosition, double sigmaSquared,
                                              double epsilon24) {
  const auto displacement = autopas::utils::ArrayMath::sub(position, otherPosition);
  const auto distanceSquared = autopas::utils::ArrayMath::dot(displacement, displacement);
  const auto inverseDistanceSquared = 1. / distanceSquared;
  const auto lj2 = sigmaSquared * inverseDistanceSquared;
  const auto lj6 = lj2 * lj2 * lj2;
  const auto lj12 = lj6 * lj6;
  const auto lj12m6 = lj12 - lj6;
  const auto scalarMultiple = epsilon24 * (lj12 + lj12m6) * inverseDistanceSquared;

  return autopas::utils::ArrayMath::mulScalar(displacement, scalarMultiple);
}

inline std::array<double, 3> calculateMirrorForce(const std::array<double, 3> &position, std::size_t dimension,
                                                  double boundaryPosition, double sigmaSquared, double epsilon24) {
  auto mirrorPosition = position;
  mirrorPosition[dimension] = 2. * boundaryPosition - position[dimension];
  return calculateLJForce(position, mirrorPosition, sigmaSquared, epsilon24);
}

/**
 * Add the repulsive Lennard-Jones force generated by a particle's mirror image.
 *
 * @tparam Particle Particle type providing addF().
 * @param particle Particle whose force is updated.
 * @param position Position of the particle.
 * @param dimension Cartesian dimension normal to the wall.
 * @param boundaryPosition Position of the reflective wall.
 * @param sigmaSquared Squared Lennard-Jones sigma value.
 * @param epsilon24 Twenty-four times the Lennard-Jones epsilon value.
 */
template <class Particle>
void addMirrorForce(Particle &particle, const std::array<double, 3> &position, std::size_t dimension,
                    double boundaryPosition, double sigmaSquared, double epsilon24) {
  particle.addF(calculateMirrorForce(position, dimension, boundaryPosition, sigmaSquared, epsilon24));
}

template <class Particle, class ParticlePropertiesLibrary>
concept SupportsMultisiteWall = requires(Particle &particle, ParticlePropertiesLibrary &particlePropertiesLibrary) {
  particle.getQuaternion();
  particle.getTorque();
  particle.addTorque(std::array<double, 3>{});
  particle.setF(particle.getF());
  particle.setTorque(particle.getTorque());
  particlePropertiesLibrary.getSitePositions(particle.getTypeId());
  particlePropertiesLibrary.getSiteTypes(particle.getTypeId());
  particlePropertiesLibrary.getMoleculesLargestSigma(particle.getTypeId());
};

/**
 * Apply the wall force for one particle, selecting the implementation from the APIs available on its types.
 *
 * Keeping this dispatch in a function template allows lightweight single-site test particles to be used even when
 * the application itself is built with multisite support.
 */
template <class Particle, class ParticlePropertiesLibrary>
void applyWallToParticle(Particle &particle, ParticlePropertiesLibrary &particlePropertiesLibrary,
                         std::size_t dimension, double boundaryPosition, bool lowerBoundary) {
  const auto moleculeType = particle.getTypeId();

  if constexpr (SupportsMultisiteWall<Particle, ParticlePropertiesLibrary>) {
    const auto currentForce = particle.getF();
    const auto currentTorque = particle.getTorque();
    const auto sitePositions = particlePropertiesLibrary.getSitePositions(moleculeType);
    const auto siteTypes = particlePropertiesLibrary.getSiteTypes(moleculeType);
    const auto rotatedSitePositions =
        autopas::utils::quaternion::rotateVectorOfPositions(particle.getQuaternion(), sitePositions);

    const auto distanceToBoundary = std::abs(particle.getR()[dimension] - boundaryPosition);
    const auto largestSigma = particlePropertiesLibrary.getMoleculesLargestSigma(moleculeType);
    if (distanceToBoundary >= sixthRootOfTwo * largestSigma * 0.5) {
      return;
    }

    std::vector<std::array<double, 3>> exactSitePositions;
    exactSitePositions.reserve(rotatedSitePositions.size());
    for (const auto &rotatedSitePosition : rotatedSitePositions) {
      exactSitePositions.push_back(autopas::utils::ArrayMath::add(particle.getR(), rotatedSitePosition));
    }

    std::vector<std::array<double, 3>> exactMirrorSitePositions;
    exactMirrorSitePositions.reserve(exactSitePositions.size());
    for (const auto &exactSitePosition : exactSitePositions) {
      auto mirrorPosition = exactSitePosition;
      const auto displacementToBoundary = boundaryPosition - exactSitePosition[dimension];
      mirrorPosition[dimension] += 2. * displacementToBoundary;
      exactMirrorSitePositions.push_back(mirrorPosition);
    }

    for (std::size_t site = 0; site < exactSitePositions.size(); ++site) {
      for (std::size_t mirrorSite = 0; mirrorSite < exactMirrorSitePositions.size(); ++mirrorSite) {
        // Keep the same site-type lookup as the reference md-flexible implementation.
        const auto siteType = siteTypes[site];
        const auto sigmaSquared = particlePropertiesLibrary.getMixingSigmaSquared(siteType, siteType);
        const auto epsilon24 = particlePropertiesLibrary.getMixing24Epsilon(siteType, siteType);
        const auto siteForce =
            calculateLJForce(exactSitePositions[site], exactMirrorSitePositions[mirrorSite], sigmaSquared, epsilon24);
        particle.addF(siteForce);
        particle.addTorque(autopas::utils::ArrayMath::cross(rotatedSitePositions[site], siteForce));
      }
    }

    const auto forceDifference = particle.getF()[dimension] - currentForce[dimension];
    const bool reflectionIsAttractive = lowerBoundary ? forceDifference < 0. : forceDifference > 0.;
    if (reflectionIsAttractive) {
      particle.setF(currentForce);
      particle.setTorque(currentTorque);
    }
  } else {
    const auto position = particle.getR();
    const auto siteType = particle.getTypeId();
    const auto distanceToBoundary = std::abs(position[dimension] - boundaryPosition);
    const auto sigma = particlePropertiesLibrary.getSigma(siteType);
    const auto repulsiveWallDistance = sixthRootOfTwo * sigma * 0.5;
    if (distanceToBoundary >= repulsiveWallDistance) {
      return;
    }

    const auto sigmaSquared = particlePropertiesLibrary.getMixingSigmaSquared(siteType, siteType);
    const auto epsilon24 = particlePropertiesLibrary.getMixing24Epsilon(siteType, siteType);
    addMirrorForce(particle, position, dimension, boundaryPosition, sigmaSquared, epsilon24);
  }
}

}  // namespace detail

/**
 * Apply reflective Lennard-Jones wall forces at reflective global boundaries touching the local domain.
 *
 * Molecules are selected by their center of mass using the maximum reflective skin. In multisite mode, each site
 * interacts with every site of the mirrored molecule. If the resulting force is attractive, the force and torque
 * contributions from that wall are discarded, matching the original md-flexible implementation.
 *
 * @tparam Container Distributed particle container type.
 * @tparam ParticlePropertiesLibrary Particle-properties library used to obtain Lennard-Jones parameters.
 * @param container Distributed particle container whose owned particles are updated.
 * @param particlePropertiesLibrary Particle-properties library for the simulated particle types.
 * @param maximumSigma Maximum Lennard-Jones sigma over all site types.
 */
template <class Container, class ParticlePropertiesLibrary>
void apply(Container &container, ParticlePropertiesLibrary &particlePropertiesLibrary, double maximumSigma) {
  const auto &boundaryTypes = container.boundaryTypes();
  const auto &globalMin = container.globalBoxMin();
  const auto &globalMax = container.globalBoxMax();
  const auto &localMin = container.localBoxMin();
  const auto &localMax = container.localBoxMax();
  const auto maximumRepulsiveWallDistance = detail::sixthRootOfTwo * maximumSigma * 0.5;
  if (maximumRepulsiveWallDistance <= 0.) {
    return;
  }

  auto applyWall = [&](std::size_t dimension, double boundaryPosition, bool lowerBoundary) {
    auto regionMin = globalMin;
    auto regionMax = globalMax;
    if (lowerBoundary) {
      regionMax[dimension] = boundaryPosition + maximumRepulsiveWallDistance;
    } else {
      regionMin[dimension] = boundaryPosition - maximumRepulsiveWallDistance;
    }

    container.applyToOwnedParticlesInRegion(regionMin, regionMax, [&](auto &particle) {
      detail::applyWallToParticle(particle, particlePropertiesLibrary, dimension, boundaryPosition, lowerBoundary);
    });
  };

  for (std::size_t dimension = 0; dimension < 3; ++dimension) {
    if (boundaryTypes[dimension] != autopasdm::BoundaryType::reflective) {
      continue;
    }

    if (autopas::utils::Math::isNearRel(localMin[dimension], globalMin[dimension])) {
      applyWall(dimension, globalMin[dimension], true);
    }

    if (autopas::utils::Math::isNearRel(localMax[dimension], globalMax[dimension])) {
      applyWall(dimension, globalMax[dimension], false);
    }
  }
}

}  // namespace ReflectiveBoundary
